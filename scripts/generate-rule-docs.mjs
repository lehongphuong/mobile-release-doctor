// Generates skills/mobile-release-doctor/references/rule-catalog.md from the
// rule YAML files so documentation can never drift from the rules.
// `--check` fails when the committed file is out of date.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";

const skill = "skills/mobile-release-doctor";
const out = join(skill, "references/rule-catalog.md");
const check = process.argv.includes("--check");

const sources = new Map(parse(readFileSync(join(skill, "policy/sources.yaml"), "utf8")).sources.map((s) => [s.id, s]));
const files = [];
const walk = (d) => {
  for (const e of readdirSync(d, { withFileTypes: true })) {
    if (e.isDirectory()) walk(join(d, e.name));
    else if (e.name.endsWith(".yaml")) files.push(join(d, e.name));
  }
};
walk(join(skill, "rules"));
const rules = files.map((f) => parse(readFileSync(f, "utf8"))).sort((a, b) => a.id.localeCompare(b.id));

const lines = [
  "# Rule catalog",
  "",
  "<!-- GENERATED by scripts/generate-rule-docs.mjs from rules/**/*.yaml — do not edit by hand. -->",
  "",
  "Statuses: `fail` (clear evidence) · `warn` (signal, confirm and fix) · `needs_review` (cannot be verified automatically) · `info`.",
  "Severities: `error` > `high` > `medium` > `low` > `info`. The engine refuses findings outside a rule's allowed statuses or above its `max_severity`.",
  "",
  "| Rule | Platforms | Requirement | Verification | Allowed statuses | Max severity |",
  "|---|---|---|---|---|---|",
  ...rules.map(
    (r) =>
      `| \`${r.id}\` | ${r.platforms.join(", ")} | ${r.requirement_status} | ${r.verification.level} | ${r.allowed_statuses.join(", ")} | ${r.max_severity} |`,
  ),
  "",
];
for (const r of rules) {
  lines.push(`## \`${r.id}\` — ${r.title}`, "");
  lines.push(r.description.trim(), "");
  lines.push(`- **Version:** ${r.version} (introduced in ${r.introduced_in}${r.deprecated_in ? `, deprecated in ${r.deprecated_in}` : ""})`);
  lines.push(`- **Frameworks:** ${r.frameworks.join(", ")}`);
  lines.push(`- **Category:** ${r.category}`);
  lines.push(`- **Requirement status:** ${r.requirement_status}; last verified ${r.verification.last_verified}`);
  if (r.applies_when?.length) lines.push(`- **Applies when:** ${r.applies_when.join(", ")}`);
  lines.push(`- **Fix:** ${r.recommendation.trim()}`);
  lines.push("- **Sources:**");
  for (const id of r.policy_references) {
    const s = sources.get(id);
    lines.push(`  - [${s.title}](${s.url})${s.last_checked ? "" : " _(URL not yet re-fetched by a maintainer)_"}`);
  }
  if (r.limitations?.length) {
    lines.push("- **Limitations:**");
    for (const l of r.limitations) lines.push(`  - ${l}`);
  }
  lines.push("");
}
const text = lines.join("\n");
if (check) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== text) {
    console.error(`${out} is out of date. Run \`npm run build\`.`);
    process.exit(1);
  }
  console.log(`${out} is up to date.`);
} else {
  writeFileSync(out, text);
  console.log(`Wrote ${out}`);
}
